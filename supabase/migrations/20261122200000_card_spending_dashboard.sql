-- Some issuers (e.g. Entercard/Trumf) print purchases as negative amounts.
-- Imported amounts are multiplied by this so purchases are always positive.
alter table public.credit_cards
  add column if not exists amount_sign smallint not null default 1
    check (amount_sign in (1, -1));

update public.credit_cards set amount_sign = -1 where name = 'Trumf Visa';

-- Fix Trumf statements imported before amount_sign existed.
update public.credit_card_transactions t
set amount = -t.amount
from public.credit_card_statements s
where s.id = t.statement_id
  and s.card_id = (select id from public.credit_cards where name = 'Trumf Visa')
  and s.total_amount < 0;

update public.credit_card_statements
set total_amount = -total_amount
where card_id = (select id from public.credit_cards where name = 'Trumf Visa')
  and total_amount < 0;

-- --------------------------------------------------
-- Categories and merchant rules
-- --------------------------------------------------

create table if not exists public.transaction_categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  color text not null default '#9ca3af',
  -- Payments to the card account are not spending.
  excluded_from_spending boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.merchant_rules (
  id bigint generated by default as identity primary key,
  -- null = built-in rule shared by all users.
  user_id uuid default auth.uid() references auth.users (id) on delete cascade,
  -- Case-insensitive POSIX regex matched against the transaction description.
  pattern text not null check (('' ~* pattern) is not null),
  category_id bigint not null references public.transaction_categories (id) on delete cascade,
  priority integer not null default 100,
  created_at timestamptz not null default now()
);

alter table public.credit_card_transactions
  add column if not exists category_id bigint
    references public.transaction_categories (id) on delete set null;

alter table public.transaction_categories enable row level security;
alter table public.merchant_rules enable row level security;

drop policy if exists "Authenticated users can read categories" on public.transaction_categories;
create policy "Authenticated users can read categories"
  on public.transaction_categories for select to authenticated using (true);

drop policy if exists "Users read built-in and own rules" on public.merchant_rules;
create policy "Users read built-in and own rules"
  on public.merchant_rules for select to authenticated
  using (user_id is null or user_id = (select auth.uid()));

drop policy if exists "Users manage own rules" on public.merchant_rules;
create policy "Users manage own rules"
  on public.merchant_rules for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

