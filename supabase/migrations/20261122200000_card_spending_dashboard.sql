-- --------------------------------------------------
-- Transactions with effective category and billing month
-- --------------------------------------------------

create or replace view public.credit_card_transactions_enriched
with (security_invoker = true) as
select
  t.id,
  t.user_id,
  t.card_id,
  card.name as card_name,
  t.statement_id,
  t.transaction_date,
  t.posting_date,
  t.description,
  t.amount,
  t.foreign_amount,
  t.foreign_currency,
  t.category_id as category_override_id,
  cat.id as category_id,
  cat.name as category_name,
  cat.color as category_color,
  cat.excluded_from_spending,
  extract(year from billing.billing_date)::integer as billing_year,
  extract(month from billing.billing_date)::integer as billing_month
from public.credit_card_transactions t
join public.credit_cards card on card.id = t.card_id
join public.credit_card_statements s on s.id = t.statement_id
left join lateral (
  select r.category_id
  from public.merchant_rules r
  where (r.user_id is null or r.user_id = t.user_id)
    and t.description ~* r.pattern
  -- User rules win over built-in rules.
  order by (r.user_id is null), r.priority, r.id
  limit 1
) rule on true
join public.transaction_categories cat
  on cat.id = coalesce(
    t.category_id,
    rule.category_id,
    (select o.id from public.transaction_categories o where o.name = 'Other')
  )
cross join lateral (
  select coalesce(
    s.due_date,
    (date_trunc('month', coalesce(s.period_end, t.transaction_date)) + interval '1 month')::date
  ) as billing_date
) billing;

grant select on public.credit_card_transactions_enriched to authenticated;
revoke all on public.credit_card_transactions_enriched from anon;

-- --------------------------------------------------
-- Card totals -> budget_entries.actual_amount (by statement due month)
-- --------------------------------------------------

create or replace function public.refresh_card_actuals()
returns integer
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_count integer;
begin
  if auth.uid() is null then
    raise exception 'Not authenticated';
  end if;

  with actuals as (
    select
      c.budget_category_id as category_id,
      e.billing_year as year,
      e.billing_month as month,
      sum(e.amount) as amount
    from public.credit_card_transactions_enriched e
    join public.credit_cards c on c.id = e.card_id
    where c.budget_category_id is not null
      and not e.excluded_from_spending
    group by 1, 2, 3
  ),
  -- Clear actuals for card months that no longer have transactions.
  cleared as (
    update public.budget_entries b
    set actual_amount = null, updated_at = now()
    where b.category_id in (
        select budget_category_id from public.credit_cards where budget_category_id is not null
      )
      and b.actual_amount is not null
      and not exists (
        select 1 from actuals a
        where a.category_id = b.category_id and a.year = b.year and a.month = b.month
      )
    returning 1
  )
  insert into public.budget_entries (category_id, year, month, budget_amount, actual_amount)
  select category_id, year, month, 0, amount
  from actuals
  on conflict (category_id, year, month)
    do update set actual_amount = excluded.actual_amount, updated_at = now();

  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

revoke all on function public.refresh_card_actuals() from public, anon;
grant execute on function public.refresh_card_actuals() to authenticated;

-- --------------------------------------------------
-- Import now stores the due date and refreshes budget actuals
-- --------------------------------------------------

drop function if exists public.import_credit_card_statement(bigint, text, text, jsonb);

create or replace function public.import_credit_card_statement(
  p_card_id bigint,
  p_file_name text,
  p_file_sha256 text,
  p_transactions jsonb,
  p_due_date date default null
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_statement_id bigint;
  v_total integer;
  v_inserted integer := 0;
begin
  if auth.uid() is null then
    raise exception 'Not authenticated';
  end if;

  if jsonb_typeof(p_transactions) is distinct from 'array'
     or jsonb_array_length(p_transactions) = 0 then
    raise exception 'No transactions to import';
  end if;

  v_total := jsonb_array_length(p_transactions);

  if exists (
    select 1 from public.credit_card_statements
    where user_id = auth.uid() and file_sha256 = p_file_sha256
  ) then
    raise exception 'This PDF has already been imported';
  end if;

  insert into public.credit_card_statements (card_id, file_name, file_sha256, due_date)
  values (p_card_id, p_file_name, p_file_sha256, p_due_date)
  returning id into v_statement_id;

  with input as (
    select
      (t ->> 'transaction_date')::date as transaction_date,
      nullif(t ->> 'posting_date', '')::date as posting_date,
      btrim(t ->> 'description') as description,
      (t ->> 'amount')::numeric(12, 2) as amount,
      coalesce(nullif(t ->> 'currency', ''), 'NOK') as currency,
      nullif(t ->> 'foreign_amount', '')::numeric(12, 2) as foreign_amount,
      nullif(t ->> 'foreign_currency', '') as foreign_currency
    from jsonb_array_elements(p_transactions) as t
  ),
  numbered as (
    select
      input.*,
      row_number() over (
        partition by transaction_date, description, amount
        order by posting_date nulls last
      )::integer as occurrence
    from input
  ),
  inserted as (
    insert into public.credit_card_transactions (
      card_id, statement_id, transaction_date, posting_date, description,
      amount, currency, foreign_amount, foreign_currency, occurrence
    )
    select
      p_card_id, v_statement_id, transaction_date, posting_date, description,
      amount, currency, foreign_amount, foreign_currency, occurrence
    from numbered
    on conflict (user_id, card_id, transaction_date, description, amount, occurrence)
      do nothing
    returning transaction_date, amount
  )
  update public.credit_card_statements s
  set
    transaction_count = agg.cnt,
    total_amount = agg.total,
    period_start = agg.min_date,
    period_end = agg.max_date
  from (
    select count(*)::integer as cnt,
           coalesce(sum(amount), 0) as total,
           min(transaction_date) as min_date,
           max(transaction_date) as max_date
    from inserted
  ) agg
  where s.id = v_statement_id
  returning s.transaction_count into v_inserted;

  if v_inserted = 0 then
    delete from public.credit_card_statements where id = v_statement_id;
    v_statement_id := null;
  else
    perform public.refresh_card_actuals();
  end if;

  return jsonb_build_object(
    'statement_id', v_statement_id,
    'inserted', v_inserted,
    'skipped', v_total - v_inserted
  );
end;
$$;

revoke all on function public.import_credit_card_statement(bigint, text, text, jsonb, date) from public, anon;
grant execute on function public.import_credit_card_statement(bigint, text, text, jsonb, date) to authenticated;
