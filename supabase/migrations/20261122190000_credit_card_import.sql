-- Credit card statement import (PDF upload -> review -> commit)

create table if not exists public.credit_cards (
  id bigint generated by default as identity primary key,
  name text not null unique,
  issuer text,
  budget_category_id bigint references public.budget_categories (id) on delete set null,
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.credit_card_statements (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  card_id bigint not null references public.credit_cards (id) on delete restrict,
  file_name text not null,
  file_sha256 text not null,
  period_start date,
  period_end date,
  transaction_count integer not null default 0,
  total_amount numeric(12, 2) not null default 0,
  created_at timestamptz not null default now(),
  unique (user_id, file_sha256)
);

create table if not exists public.credit_card_transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  card_id bigint not null references public.credit_cards (id) on delete restrict,
  statement_id bigint not null references public.credit_card_statements (id) on delete cascade,
  transaction_date date not null,
  posting_date date,
  description text not null,
  amount numeric(12, 2) not null,
  currency text not null default 'NOK',
  foreign_amount numeric(12, 2),
  foreign_currency text,
  -- Distinguishes identical purchases on the same day (e.g. two equal coffees).
  occurrence integer not null default 1,
  created_at timestamptz not null default now(),
  unique (user_id, card_id, transaction_date, description, amount, occurrence)
);

create index if not exists credit_card_transactions_date_idx
  on public.credit_card_transactions (user_id, transaction_date);
create index if not exists credit_card_transactions_statement_idx
  on public.credit_card_transactions (statement_id);

alter table public.credit_cards enable row level security;
alter table public.credit_card_statements enable row level security;
alter table public.credit_card_transactions enable row level security;

drop policy if exists "Authenticated users can read cards" on public.credit_cards;
create policy "Authenticated users can read cards"
  on public.credit_cards for select to authenticated using (true);

drop policy if exists "Users manage own statements" on public.credit_card_statements;
create policy "Users manage own statements"
  on public.credit_card_statements for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

drop policy if exists "Users manage own transactions" on public.credit_card_transactions;
create policy "Users manage own transactions"
  on public.credit_card_transactions for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

-- Imports a statement and its transactions atomically.
-- Transactions already imported from an overlapping statement are skipped.
create or replace function public.import_credit_card_statement(
  p_card_id bigint,
  p_file_name text,
  p_file_sha256 text,
  p_transactions jsonb
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_statement_id bigint;
  v_total integer;
  v_inserted integer := 0;
begin
  if auth.uid() is null then
    raise exception 'Not authenticated';
  end if;

  if jsonb_typeof(p_transactions) is distinct from 'array'
     or jsonb_array_length(p_transactions) = 0 then
    raise exception 'No transactions to import';
  end if;

  v_total := jsonb_array_length(p_transactions);

  if exists (
    select 1 from public.credit_card_statements
    where user_id = auth.uid() and file_sha256 = p_file_sha256
  ) then
    raise exception 'This PDF has already been imported';
  end if;

  insert into public.credit_card_statements (card_id, file_name, file_sha256)
  values (p_card_id, p_file_name, p_file_sha256)
  returning id into v_statement_id;

  with input as (
    select
      (t ->> 'transaction_date')::date as transaction_date,
      nullif(t ->> 'posting_date', '')::date as posting_date,
      btrim(t ->> 'description') as description,
      (t ->> 'amount')::numeric(12, 2) as amount,
      coalesce(nullif(t ->> 'currency', ''), 'NOK') as currency,
      nullif(t ->> 'foreign_amount', '')::numeric(12, 2) as foreign_amount,
      nullif(t ->> 'foreign_currency', '') as foreign_currency
    from jsonb_array_elements(p_transactions) as t
  ),
  numbered as (
    select
      input.*,
      row_number() over (
        partition by transaction_date, description, amount
        order by posting_date nulls last
      )::integer as occurrence
    from input
  ),
  inserted as (
    insert into public.credit_card_transactions (
      card_id, statement_id, transaction_date, posting_date, description,
      amount, currency, foreign_amount, foreign_currency, occurrence
    )
    select
      p_card_id, v_statement_id, transaction_date, posting_date, description,
      amount, currency, foreign_amount, foreign_currency, occurrence
    from numbered
    on conflict (user_id, card_id, transaction_date, description, amount, occurrence)
      do nothing
    returning transaction_date, amount
  )
  update public.credit_card_statements s
  set
    transaction_count = agg.cnt,
    total_amount = agg.total,
    period_start = agg.min_date,
    period_end = agg.max_date
  from (
    select count(*)::integer as cnt,
           coalesce(sum(amount), 0) as total,
           min(transaction_date) as min_date,
           max(transaction_date) as max_date
    from inserted
  ) agg
  where s.id = v_statement_id
  returning s.transaction_count into v_inserted;

  if v_inserted = 0 then
    delete from public.credit_card_statements where id = v_statement_id;
    v_statement_id := null;
  end if;

  return jsonb_build_object(
    'statement_id', v_statement_id,
    'inserted', v_inserted,
    'skipped', v_total - v_inserted
  );
end;
$$;

revoke all on function public.import_credit_card_statement(bigint, text, text, jsonb) from public, anon;
grant execute on function public.import_credit_card_statement(bigint, text, text, jsonb) to authenticated;

